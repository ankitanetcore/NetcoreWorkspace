export function emojisFor(categoryId: string, query: string): ChatEmoji[] {
  const needle = query.trim().toLowerCase();
  const source = needle
    ? emojiCategories.flatMap((category) => category.emojis)
    : (emojiCategories.find((category) => category.id === categoryId)?.emojis ?? []);
  if (!needle) {
    return source;
  }
  const seen = new Set<string>();
  return source.filter((emoji) => {
    if (seen.has(emoji.char) || !emoji.name.includes(needle)) {
      return false;
    }
    seen.add(emoji.char);
    return true;
  });
}
